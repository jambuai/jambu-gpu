"""systemd *user* units that run `gpu sweep --apply` (and `gpu guard`) on a timer.

A user unit needs no root and lives with the operator's credentials
(``~/.jambu/credentials`` or the project ``.env``). Writing the files is all
this module does; enabling them is left to the printed ``systemctl`` command.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Optional

UNIT_NAME = "jambu-gpu-sweep"
_GUARD_MARKER = " guard"


def unit_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    root = Path(base).expanduser() if base else Path.home() / ".config"
    return root / "systemd" / "user"


def unit_paths() -> tuple[Path, Path]:
    directory = unit_dir()
    return directory / f"{UNIT_NAME}.service", directory / f"{UNIT_NAME}.timer"


def _quote(arg: str) -> str:
    # systemd splits ExecStart= on whitespace and honors double quotes.
    if not arg or any(c in arg for c in ' \t"\\'):
        return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return arg


def _exec(args: list[str]) -> str:
    # "-": a failing sweep must not skip the guard lines after it.
    return "ExecStart=-" + " ".join(_quote(a) for a in args)


def _existing_guard_lines(service: Path) -> list[str]:
    if not service.is_file():
        return []
    return [
        line.strip()
        for line in service.read_text().splitlines()
        if line.startswith("ExecStart=") and line.rstrip().endswith(_GUARD_MARKER)
    ]


def render_units(
    *,
    every_s: float,
    python: str,
    working_dir: Path,
    guard_lines: list[str],
) -> tuple[str, str]:
    lines = [
        "# Generated by `gpu sweep --install-timer`. Remove with --uninstall-timer.",
        "[Unit]",
        "Description=jambu-gpu: stop/destroy GPU instances whose guard failed",
        "",
        "[Service]",
        "Type=oneshot",
        f"WorkingDirectory={working_dir}",
        _exec([python, "-m", "jambu_gpu", "sweep", "--apply"]),
        *guard_lines,
        "",
    ]
    service = "\n".join(lines)
    seconds = max(60, int(every_s))
    timer = "\n".join(
        [
            "# Generated by `gpu sweep --install-timer`.",
            "[Unit]",
            f"Description=Run {UNIT_NAME}.service every {seconds}s",
            "",
            "[Timer]",
            "OnActiveSec=60s",
            f"OnUnitActiveSec={seconds}s",
            "AccuracySec=30s",
            f"Unit={UNIT_NAME}.service",
            "",
            "[Install]",
            "WantedBy=timers.target",
            "",
        ]
    )
    return service, timer


def install_timer(
    every_s: float,
    project_config: Optional[Path] = None,
    python: Optional[str] = None,
) -> dict:
    """Write (or rewrite) the units. Guard lines of other projects are kept."""
    python = python or sys.executable
    service_path, timer_path = unit_paths()
    guards = _existing_guard_lines(service_path)
    if project_config is not None:
        config = Path(project_config).resolve()
        line = _exec([python, "-m", "jambu_gpu", "--config", str(config), "guard"])
        # Reinstalling from the same project replaces its line, not duplicates it.
        guards = [g for g in guards if _quote(str(config)) not in g] + [line]
        working_dir = config.parent
    else:
        working_dir = Path.home()
    service, timer = render_units(
        every_s=every_s, python=python, working_dir=working_dir, guard_lines=guards
    )
    service_path.parent.mkdir(parents=True, exist_ok=True)
    service_path.write_text(service)
    timer_path.write_text(timer)
    return {
        "service": str(service_path),
        "timer": str(timer_path),
        "every_s": max(60, int(every_s)),
        "guards": len(guards),
        "enable": f"systemctl --user daemon-reload && systemctl --user enable --now {UNIT_NAME}.timer",
    }


def uninstall_timer() -> dict:
    removed = []
    for path in unit_paths():
        if path.exists():
            path.unlink()
            removed.append(str(path))
    return {
        "removed": removed,
        "disable": f"systemctl --user disable --now {UNIT_NAME}.timer; systemctl --user daemon-reload",
    }
