"""Assembles the remote watchdog into a single self-contained script.

The lifecycle *policy* is owned by the core and inlined verbatim from
``core/policy.py`` so the remote guard and `gpu status` can never
disagree. The *provider actions* are injected by the adapter. Neither side
knows about the other.
"""

from __future__ import annotations

import ast
import base64
import json
import zlib
import secrets
from pathlib import Path
from typing import Optional

from ..core import policy as policy_module
from ..providers.base import WatchdogSpec

AGENT_REMOTE_PATH = "/opt/jambu/watchdog.py"
CONFIG_REMOTE_PATH = "/etc/jambu/watchdog.json"
STATE_REMOTE_PATH = "/var/lib/jambu/activity.json"
EVENTS_REMOTE_PATH = "/var/log/jambu/events.jsonl"
WATCHDOG_LOG_PATH = "/var/log/jambu/watchdog.log"
ONSTART_LOG_PATH = "/var/log/jambu/onstart.log"
SUPERVISOR_PID_PATH = "/var/run/jambu/watchdog.pid"
SUPERVISOR_RESPAWN_DELAY_S = 5

_HEADER = """#!/usr/bin/env python3
# Generated by jambu-gpu. Do not edit on the instance.
# Lifecycle policy is inlined from jambu_gpu/core/policy.py.
from __future__ import annotations
"""

_FUTURE_IMPORT = "from __future__ import annotations"

_FALLBACK_ACTIONS = '''
def provider_stop(ctx):
    raise RuntimeError("this provider supplied no stop action")


def provider_destroy(ctx):
    raise RuntimeError("this provider supplied no destroy action")
'''


def generate_token() -> str:
    """Shared secret protecting the watchdog's public control port."""
    return secrets.token_urlsafe(32)


def _strip_future(source: str) -> str:
    return "\n".join(
        line for line in source.splitlines() if line.strip() != _FUTURE_IMPORT
    )


def _compact(source: str) -> str:
    """Same code without comments or docstrings.

    The boot script rides in a size-capped provider field (Vast: 16 KB), so
    what travels is the parsed-and-unparsed source: identical semantics, none
    of the prose.
    """
    tree = ast.parse(source)
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if not isinstance(body, list) or not body:
            continue
        first = body[0]
        if (
            isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)
        ):
            node.body = body[1:] or [ast.Pass()]
    return ast.unparse(tree)


def build_agent_source(actions_source: Optional[str] = None) -> str:
    """Return the full stdlib-only watchdog script."""
    policy_source = _compact(_strip_future(Path(policy_module.__file__).read_text()))
    body_source = _compact(
        _strip_future((Path(__file__).parent / "agent_body.py").read_text())
    )
    actions = _compact(_strip_future(actions_source or _FALLBACK_ACTIONS))
    return "\n\n".join(
        [
            _HEADER,
            "# --- inlined: jambu_gpu/core/policy.py ---",
            policy_source,
            "# --- injected: provider actions ---",
            actions,
            "# --- inlined: jambu_gpu/watchdog/agent_body.py ---",
            body_source,
        ]
    )


def build_agent_config(
    *,
    provider: str,
    instance_id: str,
    token: str,
    port: int,
    interval_s: float,
    startup_grace_s: float,
    policy: "policy_module.PolicyConfig",
    created_at: float,
    watchdog_spec: Optional[WatchdogSpec] = None,
    activity_probe: Optional[dict] = None,
    runtime_pid_path: Optional[str] = None,
    runtime_log_path: Optional[str] = None,
) -> dict:
    """Config the remote agent reads at boot.

    ``activity_probe`` lets inference traffic that bypasses `gpu run` count as
    activity, e.g. ``{"kind": "prometheus", "url": ".../metrics",
    "gauges": [...], "counters": [...]}``.

    ``runtime_pid_path`` lets the agent tell a dead model server from a slow
    one; ``logs`` names the files its ``/logs`` route may serve.
    """
    logs = {"onstart": ONSTART_LOG_PATH, "watchdog": WATCHDOG_LOG_PATH}
    if runtime_log_path:
        logs["runtime"] = runtime_log_path
    config = {
        "provider": provider,
        "instance_id": instance_id,
        "token": token,
        "port": int(port),
        "interval_s": float(interval_s),
        "startup_grace_s": float(startup_grace_s),
        "created_at": float(created_at),
        "policy": policy.to_dict(),
        "env": dict(watchdog_spec.env) if watchdog_spec else {},
        "provider_context": dict(watchdog_spec.context) if watchdog_spec else {},
        "logs": logs,
    }
    if runtime_pid_path:
        config["runtime_pid_path"] = runtime_pid_path
    if activity_probe:
        config["activity_probe"] = dict(activity_probe)
    return config


def _b64_gz_block(text: str, width: int = 76) -> str:
    """Compressed, line-wrapped payload (``width=0``: one line).

    The boot script travels inside a provider API field, so the ~29 KB agent is
    deflated to ~9 KB and wrapped, instead of riding on one enormous line.
    """
    blob = base64.b64encode(zlib.compress(text.encode(), 9)).decode()
    if not width:
        return blob
    return "\n".join(blob[i : i + width] for i in range(0, len(blob), width))


def build_onstart_script(
    *,
    agent_source: str,
    agent_config: dict,
    runtime_start_command: str,
    runtime_env: Optional[dict] = None,
    watchdog_enabled: bool = True,
) -> str:
    """Bash executed on the instance right after the container comes up.

    Order matters: the watchdog starts FIRST so an instance whose model server
    fails to boot is still protected by idle/max_lifetime rules.
    """
    lines = [
        "#!/bin/bash",
        "# Generated by jambu-gpu",
        "set -u",
        # mkdir first: a failed `exec` redirect would kill a non-interactive shell.
        "mkdir -p /etc/jambu /var/lib/jambu /var/log/jambu /var/run/jambu /opt/jambu",
        f"exec >> {ONSTART_LOG_PATH} 2>&1",
        "date -u +'[%Y-%m-%dT%H:%M:%SZ] jambu onstart begin'",
    ]

    for key, value in (runtime_env or {}).items():
        lines.append(f"export {key}={_shell_quote(str(value))}")
        lines.append(f"echo {_shell_quote(f'{key}={value}')} >> /etc/jambu/runtime.env")

    if watchdog_enabled:
        # Config and agent both travel deflated; the config carries the token,
        # so it is written under a 077 umask.
        decode = (
            "import base64,os,zlib;os.umask(0o77);"
            f"[open(p,'wb').write(zlib.decompress(base64.b64decode(open(p+'.b64','rb').read())))"
            f" for p in ({CONFIG_REMOTE_PATH!r},{AGENT_REMOTE_PATH!r})]"
        )
        config_json = json.dumps(agent_config, separators=(",", ":"))
        # Killing the supervisor pid must still take the watchdog down with it:
        # the agent runs in the background so `wait` lets the TERM trap fire.
        supervisor = (
            "child=; "
            "trap '[ -n \"$child\" ] && kill \"$child\" 2>/dev/null; exit 0' TERM INT; "
            "while true; do "
            f'"$PYBIN" -u {AGENT_REMOTE_PATH} >> {WATCHDOG_LOG_PATH} 2>&1 & '
            "child=$!; "
            'wait "$child"; '
            "code=$?; "
            "date -u +\"[%Y-%m-%dT%H:%M:%SZ] jambu watchdog exited code=$code, respawning\" "
            f">> {WATCHDOG_LOG_PATH}; "
            f"sleep {SUPERVISOR_RESPAWN_DELAY_S}; "
            "done"
        )
        lines += [
            "",
            "# --- lifecycle watchdog (survives local CLI death) ---",
            "PYBIN=$(command -v python3 || command -v python)",
            'if [ -z "$PYBIN" ]; then',
            '  echo "jambu: no python interpreter in this image; watchdog NOT installed"',
            "else",
            f"  (umask 077; echo {_b64_gz_block(config_json, width=0)} > {CONFIG_REMOTE_PATH}.b64)",
            f"  cat > {AGENT_REMOTE_PATH}.b64 <<'JAMBU_AGENT_EOF'",
            _b64_gz_block(agent_source),
            "JAMBU_AGENT_EOF",
            f'  "$PYBIN" -c {_shell_quote(decode)}',
            f"  rm -f {CONFIG_REMOTE_PATH}.b64 {AGENT_REMOTE_PATH}.b64",
            f"  chmod 600 {CONFIG_REMOTE_PATH}",
            f"  chmod 700 {AGENT_REMOTE_PATH}",
            # One id per container start: the agent tells a restart (new
            # session, re-arm the guard) from a respawn (same session, keep state).
            "  export JAMBU_SESSION_STARTED_AT=$(date +%s)",
            "  export PYBIN",
            # Supervisor: a crashed watchdog must not leave the GPU unguarded.
            f"  nohup bash -c {_shell_quote(supervisor)} > /dev/null 2>&1 &",
            f"  echo $! > {SUPERVISOR_PID_PATH}",
            f'  echo "jambu: watchdog supervisor started pid $(cat {SUPERVISOR_PID_PATH})"',
            "fi",
        ]

    lines += [
        "",
        "# --- model runtime ---",
        runtime_start_command,
        "date -u +'[%Y-%m-%dT%H:%M:%SZ] jambu onstart done'",
    ]
    return "\n".join(lines) + "\n"


def _shell_quote(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"
